/* Patch runtime addresses into dsp_lst1:
 *   [12..13] NAVA.PANEL: lo/hi of nava_panel[]
 *   [72..73] JVB target:  lo/hi of dsp_lst1[] itself */
void fort8_init(void)
{
    uintptr_t np = (uintptr_t)nava_panel;
    dsp_lst1[12] = (uint8_t)(np & 0xFFu);
    dsp_lst1[13] = (uint8_t)((np >> 8) & 0xFFu);
    uintptr_t dl = (uintptr_t)dsp_lst1;
    dsp_lst1[72] = (uint8_t)(dl & 0xFFu);
    dsp_lst1[73] = (uint8_t)((dl >> 8) & 0xFFu);
}
